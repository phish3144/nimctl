# ── Throttle & chain routing: the LiteLLM hook nimctl writes ──────────────────────────────────────────────────
# $NIM_DIR/nimctl_hooks.py is one LiteLLM callback with three jobs:
#  1. Budget: NVIDIA's free tier allows roughly 40 requests per minute per key (unpublished, observed), across all
#     models. One token bucket for everything that goes to NVIDIA through the proxy: a request beyond the budget waits
#     for the next free slot instead of failing; after NIMCTL_RPM_MAX_WAIT seconds it is refused with Retry-After. An
#     upstream 429 shrinks the budget for five minutes. Requests routed to a pool provider do not touch the bucket.
#  2. Chain routing: every slot is a chain of ranks (model groups nim-<slot>, nim-<slot>-r2, …, see write_litellm_yaml);
#     a request for nim-<slot> is sent to the best rank that is not cooling down.
#  3. Cooldowns: a rank that fails (stall, 429, 5xx – also mid-stream, where LiteLLM's own cooldown does not apply to a
#     single-deployment group) is registered in LiteLLM's cooldown cache, so the fallback chain of the running request
#     and every later request skip it: RateLimitError starts at NIMCTL_COOLDOWN_RATELIMIT (20 s), timeouts/5xx at
#     NIMCTL_COOLDOWN (120 s), doubling per consecutive failure up to 30 min, cleared by a success.
# State for the dashboard and the web UI: $NIM_DIR/rpm.json (budget) and $NIM_DIR/health.json (cooldowns).
